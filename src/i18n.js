function resolveLocale(language) {
  const value = String(language || "").toLowerCase();
  if (value.startsWith("zh")) return "zh";
  if (value.startsWith("fr")) return "fr";
  if (value.startsWith("es")) return "es";
  if (value.startsWith("ja")) return "ja";
  return "en";
}

function detectLocale(getLanguage) {
  try {
    return resolveLocale(typeof getLanguage === "function" ? getLanguage() : "en");
  } catch {
    return "en";
  }
}

function format(template, variables = {}) {
  return String(template).replace(/\{([a-zA-Z]+)\}/g, (match, key) => (
    Object.prototype.hasOwnProperty.call(variables, key) ? String(variables[key]) : match
  ));
}

function createTranslator(locale = "en") {
  const selected = STRINGS[resolveLocale(locale)] || STRINGS.en;
  return (key, variables) => format(selected[key] ?? STRINGS.en[key] ?? key, variables);
}

export { createTranslator, detectLocale, resolveLocale, STRINGS };
