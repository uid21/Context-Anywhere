export const OAUTH_REFRESH_TOKEN_TTL = 365 * 24 * 60 * 60;

export function html(body, status = 200, extraHeaders = {}) {
  return new Response(body, {
    status,
    headers: {
      "cache-control": "no-store",
      "content-security-policy": "default-src 'none'; style-src 'unsafe-inline'; form-action 'self'; base-uri 'none'; frame-ancestors 'none'",
      "content-type": "text/html; charset=utf-8",
      "referrer-policy": "no-referrer",
      "x-content-type-options": "nosniff",
      "x-frame-options": "DENY",
      ...extraHeaders,
    },
  });
}

export function escapeHtml(value) {
  return String(value).replace(/[&<>"']/g, (character) => ({
    "&": "&amp;",
    "<": "&lt;",
    ">": "&gt;",
    '"': "&quot;",
    "'": "&#39;",
  })[character]);
}

// Only pass a callback validated/generated by OAUTH_PROVIDER. A fresh document
// ends the password form's navigation chain: Chromium otherwise applies
// form-action 'self' to the cross-origin HTTP redirect as well.
export function authorizationRedirect(redirectTo, extraHeaders = {}) {
  const target = escapeHtml(redirectTo);
  return html(`<!doctype html>
<html lang="zh-CN">
<head>
  <meta charset="utf-8">
  <meta name="viewport" content="width=device-width, initial-scale=1">
  <meta http-equiv="refresh" content="0;url=${target}">
  <title>正在返回客户端</title>
</head>
<body>
  <h1>正在返回客户端</h1>
  <p>如果没有自动跳转，请<a href="${target}">点击这里返回客户端</a>。</p>
</body>
</html>`, 200, {
    ...extraHeaders,
    "content-security-policy": "default-src 'none'; form-action 'none'; base-uri 'none'; frame-ancestors 'none'",
  });
}
