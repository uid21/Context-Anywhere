    internal static string Language=DetectLanguage();
    static string PreferencePath { get { return Path.Combine(Environment.GetEnvironmentVariable("CA_SETUP_DATA_DIR") ?? Path.Combine(Environment.GetFolderPath(Environment.SpecialFolder.LocalApplicationData),"ContextAnywhereSetup"),"language.txt"); } }
    internal static string Normalize(string value) { return value!=null&&value.StartsWith("zh",StringComparison.OrdinalIgnoreCase)?"zh-CN":"en"; }
    static string DetectLanguage() {
      var configured=Environment.GetEnvironmentVariable("CA_SETUP_LANGUAGE");
      if(!String.IsNullOrEmpty(configured))return Normalize(configured);
      try { var saved=File.ReadAllText(PreferencePath).Trim();if(saved=="en"||saved=="zh-CN")return saved; } catch(IOException){} catch(UnauthorizedAccessException){}
      return Normalize(CultureInfo.CurrentUICulture.Name);
    }
    internal static void Select(string value,bool persist) {
      Language=Normalize(value);if(!persist)return;
      try { Directory.CreateDirectory(Path.GetDirectoryName(PreferencePath));File.WriteAllText(PreferencePath,Language); } catch(IOException){} catch(UnauthorizedAccessException){}
    }
    internal static string T(string value) { string translated;return Language=="en"&&English.TryGetValue(value,out translated)?translated:value; }
